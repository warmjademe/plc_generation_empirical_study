#!/usr/bin/env python3
"""Build a 200-task compositional PLC challenge bank (10 categories x 20).

For each category, the five independently specified base behaviors are paired in
all 5 x 4 ordered directions.  Subsystem A drives a latched supervisory readiness
condition for subsystem B, producing 20 semantically directional compositions per
category.  OpenPLC test vectors are composed from the bases' independently authored
test oracles and explicit supervisory rules; they are not generated by executing the
composite reference implementation.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import re
from collections import Counter
from pathlib import Path
from typing import Any

from build_dataset import (
    CATEGORIES,
    PLCV_ENVIRONMENTS,
    TASKS,
    _top_level_invariant_bodies,
    default_complexity,
    properties_for,
    render_interface,
    render_reference,
    render_requirements,
    task,
)


def write_json(path: Path, value: object) -> None:
    path.write_text(json.dumps(value, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


def digest(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def supervisory_negative_control(reference: str, item: dict[str, Any]) -> dict[str, Any]:
    """Create a compile-valid, observably non-equivalent calibration sentinel.

    Every composite contract requires CrossBlocked to report an enabled but
    unready subsystem B.  The independent cross-reset OpenPLC case exercises
    exactly that state, and the native PLCverif profile contains the same
    invariant.  Mutating this assignment is therefore preferable to flipping an
    arbitrary literal that can be unreachable or observationally equivalent.
    """
    needle = "CrossBlocked := SubsystemBEnable AND (NOT CrossReady);"
    if reference.count(needle) != 1:
        raise ValueError(f"{item['id']}: expected exactly one supervisory CrossBlocked assignment")
    program = reference.replace(needle, "CrossBlocked := FALSE;", 1)
    requirement_id = item["requirements"][-1]["id"]
    return {
        "id": "NC1",
        "operator": "supervisory_blocked_stuck_false",
        "description": "Force CrossBlocked FALSE even when subsystem B is requested before readiness.",
        "target_requirement_ids": [requirement_id],
        "expected_detection": ["PLCverif", "OpenPLC"],
        "equivalence_status": "non_equivalent_by_explicit_cross_contract",
        "validation_status": "not_run",
        "program": program,
    }


def declared_name(declaration: str) -> str:
    match = re.match(r"\s*([A-Za-z_][A-Za-z0-9_]*)\s*:", declaration)
    if not match:
        raise ValueError(f"unsupported internal declaration: {declaration!r}")
    return match.group(1)


def rename_identifiers(value: str, mapping: dict[str, str]) -> str:
    pattern = re.compile(r"\b(" + "|".join(sorted((re.escape(name) for name in mapping), key=len, reverse=True)) + r")\b", re.IGNORECASE)
    folded = {name.casefold(): replacement for name, replacement in mapping.items()}
    return pattern.sub(lambda match: folded[match.group(0).casefold()], value)


def prefixed_fields(fields: list[dict[str, Any]], prefix: str) -> list[dict[str, Any]]:
    return [
        {**field, "name": f"{prefix}_{field['name']}", "description": f"Subsystem {prefix}: {field['description']}"}
        for field in fields
    ]


def mapping_for(item: dict[str, Any], prefix: str) -> dict[str, str]:
    names = [field["name"] for field in item["inputs"] + item["outputs"]]
    names.extend(declared_name(declaration) for declaration in item["internal_vars"])
    return {name: f"{prefix}_{name}" for name in names}


def prefixed_internals(item: dict[str, Any], prefix: str) -> list[str]:
    mapping = mapping_for(item, prefix)
    return [rename_identifiers(declaration, mapping) for declaration in item["internal_vars"]]


def default_for_type(plc_type: str) -> Any:
    return {"BOOL": False, "INT": 0, "DINT": 0, "REAL": 0.0}[plc_type.upper()]


def st_default(plc_type: str) -> str:
    return {"BOOL": "FALSE", "INT": "0", "DINT": "0", "REAL": "0.0"}[plc_type.upper()]


def find_activation(base: dict[str, Any]) -> tuple[str, list[dict[str, Any]]]:
    """Find an authored trace whose stated oracle activates one BOOL output."""
    bool_outputs = [field["name"] for field in base["outputs"] if field["type"].upper() == "BOOL"]
    for output in bool_outputs:
        for suite_name in ("feedback_tests", "hidden_tests"):
            for case in base[suite_name]:
                prefix = []
                for authored_step in case["steps"]:
                    prefix.append(dict(authored_step))
                    if bool(authored_step["expect"].get(output)):
                        return output, prefix
    raise ValueError(f"{base['id']} has no authored trace that activates a BOOL output")


def condition_property(expression: str, condition: str) -> str:
    bodies = _top_level_invariant_bodies(expression)
    if not bodies:
        raise ValueError(f"cannot condition non-invariant property: {expression}")
    return " AND ".join(f"G(({condition}) -> ({body}))" for body in bodies)


def renamed_requirement(requirement: dict[str, Any], mapping: dict[str, str], subsystem: str, conditioned: bool) -> dict[str, Any]:
    text = rename_identifiers(requirement["text"], mapping)
    if conditioned:
        text = f"While SubsystemBEnable and CrossReady are TRUE, subsystem B shall satisfy: {text}"
    else:
        text = f"Subsystem {subsystem} shall satisfy: {text}"
    expression = requirement.get("property")
    if expression:
        expression = rename_identifiers(expression, mapping)
        if conditioned:
            expression = condition_property(expression, "SubsystemBEnable AND CrossReady")
    return {
        "text": text,
        "property": expression,
        "safety_critical": bool(requirement.get("safety_critical", False)),
    }


def composite_input(
    a: dict[str, Any], b: dict[str, Any],
    a_values: dict[str, Any] | None = None, b_values: dict[str, Any] | None = None,
    *, b_arm: bool = False, cross_reset: bool = False,
) -> dict[str, Any]:
    values = {f"A_{field['name']}": default_for_type(field["type"]) for field in a["inputs"]}
    values.update({f"B_{field['name']}": default_for_type(field["type"]) for field in b["inputs"]})
    values.update({"SubsystemBEnable": b_arm, "CrossReset": cross_reset})
    for name, value in (a_values or {}).items():
        values[f"A_{name}"] = value
    for name, value in (b_values or {}).items():
        values[f"B_{name}"] = value
    return values


def remap_requirement_ids(requirement_ids: list[str], offset: int) -> list[str]:
    return [f"R{int(requirement_id[1:]) + offset}" for requirement_id in requirement_ids]


def safe_outputs(base: dict[str, Any], prefix: str) -> dict[str, Any]:
    return {f"{prefix}_{field['name']}": default_for_type(field["type"]) for field in base["outputs"]}


def mapped_step(
    a: dict[str, Any], b: dict[str, Any], authored_step: dict[str, Any], subsystem: str,
    *, held_a: dict[str, Any] | None = None, b_arm: bool = False, cross_reset: bool = False,
) -> dict[str, Any]:
    if subsystem == "A":
        inputs = composite_input(a, b, a_values=authored_step["inputs"], b_arm=b_arm, cross_reset=cross_reset)
        expect = {f"A_{name}": value for name, value in authored_step["expect"].items()}
        expect.update(safe_outputs(b, "B"))
        expect["CrossBlocked"] = bool(b_arm)
    elif subsystem == "B":
        if held_a is None:
            raise ValueError("subsystem-B oracle step requires held subsystem-A inputs")
        inputs = composite_input(
            a, b, a_values=held_a, b_values=authored_step["inputs"],
            b_arm=b_arm, cross_reset=cross_reset,
        )
        expect = {f"B_{name}": value for name, value in authored_step["expect"].items()}
        expect.update({"CrossReady": not cross_reset, "CrossBlocked": bool(b_arm and cross_reset)})
        if cross_reset or not b_arm:
            expect.update(safe_outputs(b, "B"))
    else:
        raise ValueError(f"unknown subsystem {subsystem}")
    return {
        "inputs": inputs,
        "expect": expect,
        "repeat": int(authored_step["repeat"]),
        "check": authored_step["check"],
    }


def activation_steps(a: dict[str, Any], b: dict[str, Any], activation: list[dict[str, Any]]) -> list[dict[str, Any]]:
    steps = [mapped_step(a, b, authored_step, "A") for authored_step in activation]
    steps[-1]["expect"]["CrossReady"] = True
    return steps


def build_openplc_suite(
    item: dict[str, Any], a: dict[str, Any], b: dict[str, Any], activation: list[dict[str, Any]],
) -> dict[str, Any]:
    cases: list[dict[str, Any]] = []
    a_count = len(a["requirements"])
    held_a = dict(activation[-1]["inputs"])
    for suite_name in ("feedback_tests", "hidden_tests"):
        label = "feedback" if suite_name == "feedback_tests" else "hidden"
        for index, case in enumerate(a[suite_name], start=1):
            cases.append({
                "name": f"A_{label}_{index}",
                "description": "Subsystem-A expectations are copied from its independently authored base oracle.",
                "requirement_ids": remap_requirement_ids(case["requirement_ids"], 0),
                "fresh_instance": True,
                "steps": [mapped_step(a, b, authored_step, "A") for authored_step in case["steps"]],
                "oracle_source": "independent_base_oracle_A",
            })
        for index, case in enumerate(b[suite_name], start=1):
            steps = activation_steps(a, b, activation)
            steps.extend(
                mapped_step(a, b, authored_step, "B", held_a=held_a, b_arm=True)
                for authored_step in case["steps"]
            )
            cases.append({
                "name": f"B_{label}_{index}",
                "description": "Subsystem-B expectations are copied from its independent base oracle after an authored A activation trace.",
                "requirement_ids": remap_requirement_ids(case["requirement_ids"], a_count),
                "fresh_instance": True,
                "steps": steps,
                "oracle_source": "independent_base_oracle_B_after_A_activation",
            })

    probe = b["feedback_tests"][0]
    probe_step = dict(probe["steps"][0])
    reset_step = mapped_step(a, b, probe_step, "B", held_a=held_a, b_arm=True, cross_reset=True)
    reset_step["expect"] = {
        **safe_outputs(b, "B"),
        "CrossReady": False,
        "CrossBlocked": True,
    }
    cross_requirement_ids = [f"R{index}" for index in range(len(item["requirements"]) - 3, len(item["requirements"]) + 1)]
    cases.append({
        "name": "cross_reset_priority",
        "description": "The explicitly specified supervisory reset isolates B in the same scan.",
        "requirement_ids": cross_requirement_ids,
        "fresh_instance": True,
        "steps": activation_steps(a, b, activation) + [
            mapped_step(a, b, probe_step, "B", held_a=held_a, b_arm=True),
            reset_step,
        ],
        "oracle_source": "independently_specified_supervisory_contract",
    })
    for index, case in enumerate(cases, start=1):
        case["id"] = f"OT{index:02d}"
    return {
        "schema_version": "1.0",
        "suite": "openplc",
        "task_id": item["id"],
        "scan_period_ms": item["scan_period_ms"],
        "real_absolute_tolerance": item["real_tolerance"],
        "oracle_source": "independent_base_oracles_plus_explicit_composition_rules",
        "independent_requirement_oracle": True,
        "cases": cases,
    }


def composite_environment(a: dict[str, Any], b: dict[str, Any], map_a: dict[str, str], map_b: dict[str, str]) -> dict[str, Any]:
    result: dict[str, Any] = {"parameters": [], "assumption_invariants": []}
    for base, mapping in ((a, map_a), (b, map_b)):
        environment = base.get("plcverif_environment", PLCV_ENVIRONMENTS.get(base["id"], {}))
        result["parameters"].extend(mapping.get(name, name) for name in environment.get("parameters", []))
        result["assumption_invariants"].extend(
            rename_identifiers(expression, mapping)
            for expression in environment.get("assumption_invariants", [])
        )
        if "cbmc_unwind" in environment:
            result["cbmc_unwind"] = max(int(result.get("cbmc_unwind", 0)), int(environment["cbmc_unwind"]))
    result["parameters"] = list(dict.fromkeys(result["parameters"]))
    result["assumption_invariants"] = list(dict.fromkeys(result["assumption_invariants"]))
    return result


def compose(a: dict[str, Any], b: dict[str, Any], task_id: str) -> dict[str, Any]:
    map_a = mapping_for(a, "A")
    map_b = mapping_for(b, "B")
    control_name, activation = find_activation(a)
    a_control = map_a[control_name]
    safe_b_property = " AND ".join(
        f"NOT B_{field['name']}" if field["type"].upper() == "BOOL"
        else f"B_{field['name']}={st_default(field['type'])}"
        for field in b["outputs"]
    )
    requirements = []
    requirements.extend(renamed_requirement(requirement, map_a, "A", False) for requirement in a["requirements"])
    requirements.extend(renamed_requirement(requirement, map_b, "B", True) for requirement in b["requirements"])
    requirements.extend([
        {
            "text": f"A TRUE {a_control} shall latch CrossReady unless CrossReset is TRUE in the same scan.",
            "property": f"G(CrossReset -> !CrossReady) AND G(({a_control} AND !CrossReset)->CrossReady)",
            "safety_critical": True,
        },
        {
            "text": "CrossReset shall have priority, clear CrossReady, and isolate every subsystem-B output to its type-safe default.",
            "property": (
                f"G(CrossReset -> (!CrossReady AND {safe_b_property})) AND "
                f"G((NOT (SubsystemBEnable AND CrossReady)) -> ({safe_b_property}))"
            ),
            "safety_critical": True,
        },
        {
            "text": "Once set, CrossReady shall remain TRUE after the subsystem-A signal falls, until a later CrossReset scan.",
            "property": "G((CrossReady AND !CrossReset)->X(CrossReady))",
            "safety_critical": False,
        },
        {
            "text": "Subsystem B may execute only while SubsystemBEnable and CrossReady are TRUE; CrossBlocked is TRUE exactly when SubsystemBEnable is requested without CrossReady.",
            "property": "G(CrossBlocked = (SubsystemBEnable AND !CrossReady))",
            "safety_critical": True,
        },
    ])
    a_body = rename_identifiers(a["body"], map_a)
    b_body = rename_identifiers(b["body"], map_b)
    safe_b = "\n".join(f"    B_{field['name']} := {st_default(field['type'])};" for field in b["outputs"])
    body = f"""{a_body}

IF CrossReset THEN
    CrossReady := FALSE;
ELSIF {a_control} THEN
    CrossReady := TRUE;
END_IF;
CrossBlocked := SubsystemBEnable AND (NOT CrossReady);

IF SubsystemBEnable AND CrossReady THEN
{chr(10).join('    ' + line if line.strip() else line for line in b_body.splitlines())}
ELSE
{safe_b}
END_IF;"""
    complexity_a, complexity_b = default_complexity(a), default_complexity(b)
    item = task(
        task_id,
        f"Composed supervisory control: {a['title']} -> {b['title']}",
        a["category_id"], "hard",
        prefixed_fields(a["inputs"], "A") + prefixed_fields(b["inputs"], "B") + [
            {"name": "SubsystemBEnable", "type": "BOOL", "description": "Request execution of subsystem B"},
            {"name": "CrossReset", "type": "BOOL", "description": "High-priority supervisory readiness reset"},
        ],
        prefixed_fields(a["outputs"], "A") + prefixed_fields(b["outputs"], "B") + [
            {"name": "CrossReady", "type": "BOOL", "description": f"Latched observation of {a_control}"},
            {"name": "CrossBlocked", "type": "BOOL", "description": "SubsystemBEnable is requested without CrossReady"},
        ],
        requirements,
        body,
        [], [],
        internal_vars=prefixed_internals(a, "A") + prefixed_internals(b, "B"),
        iec_features=sorted(set(a["iec_features"] + b["iec_features"] + ["compositional control", "supervisory interlock", "latched readiness"])),
        assumptions=list(dict.fromkeys(
            [f"Subsystem A: {rename_identifiers(value, map_a)}" for value in a["assumptions"]]
            + [f"Subsystem B: {rename_identifiers(value, map_b)}" for value in b["assumptions"]]
            + [
            "Subsystem A executes before the supervisory latch and subsystem B within each scan.",
            "Requirements inherited from subsystem B apply only while SubsystemBEnable and CrossReady are TRUE.",
            "When subsystem B is isolated, its externally visible outputs take their type-safe defaults.",
        ])),
        complexity={
            "retained_state": complexity_a["retained_state"] + complexity_b["retained_state"] + 1,
            "transitions": complexity_a["transitions"] + complexity_b["transitions"] + 3,
            "stateful_blocks": complexity_a["stateful_blocks"] + complexity_b["stateful_blocks"],
            "interactions": complexity_a["interactions"] + complexity_b["interactions"] + 5,
            "fault_modes": complexity_a["fault_modes"] + complexity_b["fault_modes"] + 2,
            "horizon_scans": max(complexity_a["horizon_scans"], complexity_b["horizon_scans"]) + 4,
        },
        scan_period_ms=max(a["scan_period_ms"], b["scan_period_ms"]),
        real_tolerance=max(a["real_tolerance"], b["real_tolerance"]),
    )
    item["plcverif_environment"] = composite_environment(a, b, map_a, map_b)
    item["openplc_tests"] = build_openplc_suite(item, a, b, activation)
    item["composition"] = {
        "base_a": a["id"], "base_b": b["id"], "direction": "A_to_B",
        "activation_output": a_control,
    }
    return item


def write_task(root: Path, item: dict[str, Any]) -> dict[str, Any]:
    task_dir = root / item["id"]
    task_dir.mkdir()
    reference = render_reference(item)
    metadata = {
        "schema_version": "1.0", "dataset_version": "bank-0.3.1-dev", "id": item["id"],
        "title": item["title"], "category_id": item["category_id"], "category": CATEGORIES[item["category_id"]],
        "difficulty_stratification": "not_used", "iec_profile": "IEC-ST Core v1", "iec_features": item["iec_features"],
        "complexity": default_complexity(item), "interface": {"inputs": item["inputs"], "outputs": item["outputs"]},
        "scan": {"period_ms": item["scan_period_ms"], "input_sampling": "scan_start", "output_observation": "scan_end", "initialization": "fresh function-block instance for every test case"},
        "assumptions": item["assumptions"], "requirements": item["requirements"],
        "composition": item["composition"],
        "provenance": {"origin": "deterministic ordered composition of independently specified base behaviors", "public_before_evaluation": False, "license": "research-internal; public license pending"},
        "review": {"author_review": "pending", "independent_review": "pending"},
    }
    (task_dir / "requirement.md").write_text(render_requirements(item), encoding="utf-8")
    (task_dir / "interface.st").write_text(render_interface(item), encoding="utf-8")
    (task_dir / "reference.st").write_text(reference, encoding="utf-8")
    write_json(task_dir / "metadata.json", metadata)
    write_json(task_dir / "properties.json", properties_for(item))
    write_json(task_dir / "openplc_tests.json", item["openplc_tests"])
    control = supervisory_negative_control(reference, item)
    control_dir = task_dir / "negative_control"
    control_dir.mkdir()
    (control_dir / "NC1.st").write_text(control.pop("program"), encoding="utf-8")
    write_json(control_dir / "index.json", {"purpose": "oracle calibration only; no LLM call", "count": 1, "controls": [control]})
    write_json(task_dir / "validation_report.json", {
        "schema_version": "1.0", "task_id": item["id"], "structural": {"status": "not_run"},
        "external": {name: {"status": "not_run"} for name in ("matiec", "plcverif", "openplc")},
        "screening": {"kimi_k3_direct_once": "not_run"},
    })
    artifacts = ["metadata.json", "requirement.md", "interface.st", "reference.st", "properties.json", "openplc_tests.json", "negative_control/index.json", "negative_control/NC1.st"]
    return {
        "id": item["id"], "category_id": item["category_id"], "path": f"tasks/{item['id']}",
        "base_a": item["composition"]["base_a"], "base_b": item["composition"]["base_b"],
        "hashes": {name: digest(task_dir / name) for name in artifacts},
    }


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--output", required=True, type=Path)
    args = parser.parse_args()
    output = args.output.resolve()
    if output.exists():
        raise FileExistsError(f"refusing to overwrite task bank {output}")
    task_root = output / "tasks"
    task_root.mkdir(parents=True)
    by_category = {category: sorted([item for item in TASKS if item["category_id"] == category], key=lambda item: item["id"]) for category in CATEGORIES}
    if any(len(items) != 5 for items in by_category.values()):
        raise ValueError("base dataset must contain exactly five behaviors per category")
    records = []
    for category, bases in by_category.items():
        ordered_pairs = [(left, right) for left in bases for right in bases if left["id"] != right["id"]]
        for index, (left, right) in enumerate(ordered_pairs, start=1):
            task_id = f"{category}_B{index:02d}_composite"
            item = compose(left, right, task_id)
            records.append(write_task(task_root, item))
            print(json.dumps({"task_id": task_id, "base_a": left["id"], "base_b": right["id"]}, ensure_ascii=False), flush=True)
    if len(records) != 200:
        raise AssertionError(f"expected 200 tasks, built {len(records)}")
    with (output / "manifest.jsonl").open("w", encoding="utf-8") as handle:
        for record in records:
            handle.write(json.dumps(record, ensure_ascii=False, sort_keys=True) + "\n")
    write_json(output / "dataset_summary.json", {
        "dataset": "IEC-ST-VerifyBench-TaskBank", "version": "0.3.1-dev", "task_count": 200,
        "category_counts": dict(sorted(Counter(record["category_id"] for record in records).items())),
        "difficulty_stratification": "not_used",
        "construction_rule": "all ordered non-self pairs among five base behaviors in each category",
        "openplc_oracle": "independent base oracles plus explicit composition rules",
        "screening_model": "kimi-k3", "screening_attempts_per_task": 1,
        "selection_target": 50, "selection_quota_per_category": 5,
        "selection_status": "not_run", "model_calls_used_to_build_oracles": False,
    })
    print(f"Built {len(records)} frozen pre-screen tasks at {output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
